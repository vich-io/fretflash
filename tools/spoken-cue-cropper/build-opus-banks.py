"""Package accepted WAV banks as the selected 64-kbps Opus, with WebM timing."""
from pathlib import Path
import hashlib
import json
import subprocess
import tempfile
import wave

ROOT = Path(__file__).resolve().parents[2]
MODULE = ROOT / 'src/voice-bank.js'
BANKS = [('natural', 'SPOKEN_BANK'), ('fast', 'SPOKEN_FAST_BANK'), ('tight', 'SPOKEN_TIGHT_BANK')]
metadata = json.loads(subprocess.check_output([
    'node', '--input-type=module', '-e',
    "import {SPOKEN_BANK,SPOKEN_FAST_BANK,SPOKEN_TIGHT_BANK} from './src/voice-bank.js'; console.log(JSON.stringify({natural:SPOKEN_BANK,fast:SPOKEN_FAST_BANK,tight:SPOKEN_TIGHT_BANK}));"
], cwd=ROOT))


def ffmpeg(args, **kwargs):
    return subprocess.run(['ffmpeg', '-nostdin', '-hide_banner', '-loglevel', 'error', '-y', *args], check=True, **kwargs)


report = {}
with tempfile.TemporaryDirectory(prefix='fretflash-opus-') as directory:
    directory = Path(directory)
    for name, _ in BANKS:
        bank = metadata[name]
        source = ROOT / Path(bank['path']).with_suffix('.wav')
        with wave.open(str(source), 'rb') as wav:
            assert (wav.getnchannels(), wav.getsampwidth(), wav.getframerate(), wav.getnframes()) == (1, 2, bank['sampleRate'], bank['frames'])
        pcm = directory / f'{name}.f32'
        opus = directory / f'{name}.opus'
        # Match the accepted audition's resampling and encoding exactly.
        ffmpeg(['-i', str(source), '-af', 'aresample=48000:resampler=soxr:precision=28', '-f', 'f32le', '-c:a', 'pcm_f32le', str(pcm)])
        ffmpeg(['-f', 'f32le', '-ar', '48000', '-ac', '1', '-i', str(pcm), '-c:a', 'libopus', '-b:a', '64k', '-vbr', 'on', '-application', 'audio', '-compression_level', '10', str(opus)])
        target = source.with_suffix('.webm')
        # Chromium drops Opus pre-skip twice in Ogg; WebM retains the correct
        # complete duration and alignment. Copy packets, never re-encode here.
        ffmpeg(['-i', str(opus), '-c:a', 'copy', '-map_metadata', '-1', '-fflags', '+bitexact', str(target)])
        bank['path'] = target.relative_to(ROOT).as_posix()
        report[name] = {'path': bank['path'], 'bytes': target.stat().st_size, 'sha256': hashlib.sha256(target.read_bytes()).hexdigest()}
MODULE.write_text('// Generated by tools/spoken-cue-cropper/build-bank.py; frame offsets are half-open.\n' + ''.join(
    f'export const {constant} = ' + json.dumps(metadata[name], indent=2) + ';\n' for name, constant in BANKS
))
print(json.dumps({'codec': 'Opus 64 kbps VBR, mono 48 kHz, WebM', 'banks': report, 'audioBytes': sum(bank['bytes'] for bank in report.values())}, indent=2))
